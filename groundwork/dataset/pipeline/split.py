"""Stage 2: split dataset/raw into train/val at the IMAGE level + write data.yaml.

Whole images go to one side only — never crops/dupes of the same image in both
sets, or val accuracy is a fiction. The split is STABLE per image (see
_val_rank), so adding/removing images moves only those images. Optional
--val-list pins the hard/dense images into val so the eval is honest.

    python -m groundwork.dataset.pipeline.split --project <slug> --val-frac 0.2
    python -m groundwork.dataset.pipeline.split --project <slug> --val-list IMG_4372
"""
from __future__ import annotations
import argparse
import hashlib
import shutil

from .. import paths


def _stems_with_labels(pp) -> list[str]:
    """Image stems that have a matching label file in dataset/raw.

    Ignores 'classes.txt' — labelImg drops one into the save dir on save, and it
    is not a per-image label.
    """
    label_stems = {p.stem for p in pp.RAW_LABELS.glob("*.txt")
                   if p.stem != "classes"}
    return sorted(p.stem for p in pp.RAW_IMAGES.iterdir()
                  if p.is_file() and p.stem in label_stems)


def _img_path(stem: str, pp):
    for p in pp.RAW_IMAGES.glob(f"{stem}.*"):
        return p
    return None


def _count_boxes(stem: str, pp) -> int:
    txt = (pp.RAW_LABELS / f"{stem}.txt").read_text(encoding="utf-8").strip()
    return len([ln for ln in txt.splitlines() if ln.strip()])


def _place(stems: list[str], split: str, pp) -> int:
    img_dst = pp.IMAGES_DIR / split
    lbl_dst = pp.LABELS_DIR / split
    for d in (img_dst, lbl_dst):
        d.mkdir(parents=True, exist_ok=True)
    boxes = 0
    for stem in stems:
        src_img = _img_path(stem, pp)
        shutil.copy2(src_img, img_dst / src_img.name)
        shutil.copy2(pp.RAW_LABELS / f"{stem}.txt", lbl_dst / f"{stem}.txt")
        boxes += _count_boxes(stem, pp)
    return boxes


def _val_rank(stem: str, seed: int) -> str:
    """Stable sort key per image — hashed from the NAME, not the list position.

    Shuffling a list re-permutes EVERY image as soon as its length changes, so
    moving a single image into the holdout silently rebuilt the whole val
    split. That split drives early stopping and which epoch ultralytics saves
    as best.pt, so an unrelated image move could (and once did) freeze an
    undertrained checkpoint and make MAE incomparable across runs. Hashing the
    name pins each image's side for good; only the images you actually move can
    change sides.
    """
    return hashlib.md5(f"{seed}:{stem}".encode()).hexdigest()


def select_val(stems: list[str], val_frac: float = 0.2, seed: int = 0,
               val_list: list[str] | None = None) -> list[str]:
    """Which images go to VAL — the ONE definition of that rule.

    Extracted so altmodels/convert.py can call it instead of re-implementing
    it: two independent copies of this rule once produced different val sets,
    and then the champion and the challenger were early-stopped and
    best.pt-selected on different images, making every MAE comparison between
    them meaningless.
    """
    if val_list:
        pinned = [s for s in val_list if s in stems]
        rest = sorted((s for s in stems if s not in pinned),
                      key=lambda s: _val_rank(s, seed))
        n_more = max(0, round(val_frac * len(stems)) - len(pinned))
        return pinned + rest[:n_more]
    n_val = max(1, round(val_frac * len(stems)))
    return sorted(stems, key=lambda s: _val_rank(s, seed))[:n_val]


def _write_yaml(pp) -> None:
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(pp.CLASS_NAMES))
    pp.DATA_YAML.write_text(
        f"# auto-generated by groundwork.dataset.pipeline.split\n"
        f"path: {pp.DATASET_DIR}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"nc: {len(pp.CLASS_NAMES)}\n"
        f"names:\n{names}\n",
        encoding="utf-8",
    )


def is_current(pp, val_frac: float = 0.2, seed: int = 0,
               val_list: list[str] | None = None) -> tuple[bool, str]:
    """Would build_split() produce exactly what is already on disk?

    WHY THIS EXISTS. Re-splitting is destructive before it is constructive: it
    rmtree's images/{train,val} and labels/{train,val} and rebuilds them. That
    is fine on an idle machine and fatal on a busy one, because a retrain
    trains FROM those directories — which is why launching a challenger during
    a retrain was refused outright, per-card GPU locks notwithstanding.

    But membership is deterministic: _val_rank is a seeded hash of the stem, so
    the same image set always yields the same split. When the tree on disk
    already IS what a fresh split would build, the rmtree destroys and
    recreates identical files for no gain — and skipping it lets a challenger
    start on the other card while a retrain runs, which is the whole point of
    two GPUs.

    Returns (current, why-not). The reason is shown to the user, because "your
    split is stale" and "the machine is busy" call for completely different
    responses: wait, versus add the missing images and try again.

    COMPARED BY LABEL FILES, not images. Every image has exactly one .txt by
    construction, while an image may be .jpg or .png and _place copies whatever
    extension it found — matching on image names would report a spurious
    difference the moment someone re-uploads an image in another format.
    """
    stems = _stems_with_labels(pp)
    if not stems:
        return False, "no labelled images in raw/"
    want_val = set(select_val(stems, val_frac, seed, val_list))
    want = {"val": want_val, "train": set(stems) - want_val}
    for split in ("train", "val"):
        d = pp.LABELS_DIR / split
        if not d.is_dir():
            return False, f"{split} split has never been built here"
        have = {p.stem for p in d.glob("*.txt") if p.stem != "classes"}
        if have != want[split]:
            missing, extra = len(want[split] - have), len(have - want[split])
            bits = []
            if missing:
                bits.append(f"{missing} image(s) missing from {split}")
            if extra:
                bits.append(f"{extra} no longer in the dataset")
            return False, ", ".join(bits) + f" (on disk {len(have)}, "\
                                            f"expected {len(want[split])})"
    return True, ""


def build_split(pp, val_frac: float = 0.2, seed: int = 0,
                val_list: list[str] | None = None) -> None:
    stems = _stems_with_labels(pp)
    if not stems:
        raise SystemExit(f"No labeled images in {pp.RAW_DIR}. Label some first.")

    # Guard: no label line may name a class this project does not declare.
    # ultralytics silently DROPS an image whose label exceeds nc ("class
    # exceeds nc") — the image vanishes from training with no error at all,
    # which is this repo's worst failure shape. Fail loudly instead of training
    # blind. THE BOUND IS THE PROJECT'S, not a hardcoded 0: for a project that
    # declares three classes, 1 and 2 are exactly what it is FOR.
    nc = len(pp.CLASS_NAMES)
    bad = {}
    for s in stems:
        over = sorted({ln.split()[0]
                       for ln in (pp.RAW_LABELS / f"{s}.txt").read_text().splitlines()
                       if ln.strip() and not (ln.split()[0].isdigit()
                                              and int(ln.split()[0]) < nc)})
        if over:
            bad[s] = over
    if bad:
        names = ", ".join(f"{s} (cls {'/'.join(v)})"
                          for s, v in sorted(bad.items())[:8])
        extra = "…" if len(bad) > 8 else ""
        raise SystemExit(
            f"[split] {len(bad)} image(s) carry label lines outside this "
            f"project's {nc} class(es): {names}{extra}\n"
            f"[split] This project declares {nc} class(es) "
            f"({', '.join(pp.CLASS_NAMES)}), so valid indices are 0-{nc - 1}. "
            f"Fix the labels (or the project's class list) and re-run split.")

    # Fresh split dirs each run so re-splitting can't leave stale files behind.
    for split in ("train", "val"):
        shutil.rmtree(pp.IMAGES_DIR / split, ignore_errors=True)
        shutil.rmtree(pp.LABELS_DIR / split, ignore_errors=True)

    val = select_val(stems, val_frac, seed, val_list)

    train = [s for s in stems if s not in set(val)]
    assert not (set(train) & set(val)), "image leaked into both splits"

    tb = _place(train, "train", pp)
    vb = _place(val, "val", pp)
    _write_yaml(pp)
    print(f"[split] train: {len(train)} images / {tb} boxes | "
          f"val: {len(val)} images / {vb} boxes")
    print(f"[split] val images: {sorted(val)}")
    print(f"[split] wrote {pp.DATA_YAML}")

    # Guardrail: flag any image that looks like the SAME scene in both train
    # and test (a different-filename re-shoot slips past the exclusive-bucket
    # rule). Best-effort. `pp=pp` is load-bearing: without it these would read
    # a different project's tree.
    try:
        from ..viz import dedup_check
        dups = dedup_check.near_duplicates("raw", "testset", pp=pp)
        if dups:
            print(f"[split] ⚠ {len(dups)} possible train/test DUPLICATE(s) — same scene "
                  f"in both buckets (a leak). Run `python -m groundwork.dataset.viz.dedup_check`:")
            for sa, sb, d in dups[:5]:
                print(f"[split]    {sa} ~ {sb} (dist {d})")
        selfd = dedup_check.near_duplicates("raw", "raw", pp=pp)
        if selfd:
            print(f"[split] ⚠ {len(selfd)} duplicate image(s) WITHIN training (same scene "
                  f"twice — redundant). Remove one of each:")
            for sa, sb, d in selfd[:5]:
                print(f"[split]    {sa} ~ {sb} (dist {d})")
    except Exception:  # noqa: BLE001
        pass


def main() -> None:
    ap = argparse.ArgumentParser(description="Image-level train/val split + data.yaml.")
    ap.add_argument("--val-frac", type=float, default=0.2)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--val-list", nargs="*", default=None,
                    help="stems to force into val (e.g. dense/hard images)")
    from ...project import add_argument, load
    add_argument(ap)
    args = ap.parse_args()
    proj = load(args.project)
    # SAY WHICH DATASET. The most expensive failure mode in this repo is a job
    # that quietly ran on the wrong data. With more than one project that risk
    # grows a second dimension, so every stage announces its project and root
    # up front.
    print(f"[split] project {proj.slug} ({proj.name}) | classes {list(proj.classes)} "
          f"| {proj.dataset_root}")
    build_split(paths.for_project(proj), args.val_frac, args.seed, args.val_list)


if __name__ == "__main__":
    main()
